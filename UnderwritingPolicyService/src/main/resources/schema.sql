-- =========================================================
-- POLICIES TABLE
-- =========================================================

CREATE TABLE IF NOT EXISTS policies (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                        business_id BIGINT NOT NULL,
                                        owner_id BIGINT NOT NULL,

                                        policy_number VARCHAR(100) NOT NULL UNIQUE,
    policy_type VARCHAR(50) NOT NULL,

    coverage_amount DECIMAL(19,2) NOT NULL,
    coverage_details VARCHAR(1000),
    coverage_location VARCHAR(255),

    premium_amount DECIMAL(19,2) NOT NULL,

    start_date DATE NOT NULL,
    end_date DATE NOT NULL,

    tenure_value INT NOT NULL DEFAULT 1,
    tenure_unit VARCHAR(10) NOT NULL DEFAULT 'YEARS',
    payment_frequency VARCHAR(10) NOT NULL DEFAULT 'YEARLY',

    status VARCHAR(30) NOT NULL,
    description VARCHAR(1000),

    -- Policy cancellation support
    previous_status VARCHAR(30),
    cancellation_reason VARCHAR(1000),

    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
    );


