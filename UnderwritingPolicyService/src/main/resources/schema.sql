-- =========================================================
-- POLICY INDEXES
-- =========================================================

CREATE UNIQUE INDEX IF NOT EXISTS idx_policy_number
    ON policies(policy_number);

CREATE INDEX IF NOT EXISTS idx_policy_owner
    ON policies(owner_id);

CREATE INDEX IF NOT EXISTS idx_policy_business
    ON policies(business_id);


-- =========================================================
-- MOCK PAYMENT RECORDS
-- =========================================================

CREATE TABLE IF NOT EXISTS policy_payments (
                                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                               policy_id BIGINT NOT NULL,
                                               owner_id BIGINT NOT NULL,

                                               amount DECIMAL(19,2) NOT NULL,
    payment_date TIMESTAMP NOT NULL,

    status VARCHAR(30) NOT NULL,
    transaction_reference VARCHAR(100) NOT NULL UNIQUE,

    created_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_payment_policy
    FOREIGN KEY (policy_id)
    REFERENCES policies(id)
    );


-- =========================================================
-- PAYMENT INDEXES
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_payment_policy
    ON policy_payments(policy_id);

CREATE INDEX IF NOT EXISTS idx_payment_owner
    ON policy_payments(owner_id);

CREATE INDEX IF NOT EXISTS idx_payment_status
    ON policy_payments(status);